create or replace function public.upsert_dashboard_ga4_acquisition_batch(
  p_client_slug text,
  p_account_id text,
  p_idempotency_key text,
  p_range_start date,
  p_range_end date,
  p_rows jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_client_id bigint;
  v_rows jsonb := coalesce(p_rows, '[]'::jsonb);
  v_row_count integer;
  v_existing public.dashboard_sync_runs%rowtype;
begin
  if p_range_start is null or p_range_end is null or p_range_start > p_range_end then
    raise exception 'invalid date range' using errcode = '22023';
  end if;
  if p_account_id is null or btrim(p_account_id) = '' then
    raise exception 'account id is required' using errcode = '22023';
  end if;
  if p_idempotency_key is null or length(btrim(p_idempotency_key)) not between 8 and 240 then
    raise exception 'invalid idempotency key' using errcode = '22023';
  end if;
  if jsonb_typeof(v_rows) <> 'array' or jsonb_array_length(v_rows) = 0 then
    raise exception 'acquisition batch cannot be empty' using errcode = '22023';
  end if;

  select dc.id into v_client_id
  from public.dashboard_clients dc
  where dc.slug = p_client_slug and dc.active;
  if v_client_id is null then
    raise exception 'dashboard client not found or inactive' using errcode = '22023';
  end if;

  select * into v_existing
  from public.dashboard_sync_runs dsr
  where dsr.client_id = v_client_id
    and dsr.source = 'ga4'
    and dsr.idempotency_key = p_idempotency_key;
  if found then
    return jsonb_build_object(
      'success', true, 'idempotent', true, 'dataset', 'acquisition',
      'rows', v_existing.daily_rows, 'range_start', v_existing.range_start,
      'range_end', v_existing.range_end
    );
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(v_rows) as r(
      account_id text, metric_date date, channel_group text, source_medium text,
      sessions bigint, engaged_sessions bigint, new_users bigint,
      views bigint, events bigint, key_events numeric
    )
    where r.metric_date is null
       or r.metric_date < p_range_start or r.metric_date > p_range_end
       or r.channel_group is null or btrim(r.channel_group) = ''
       or r.source_medium is null or btrim(r.source_medium) = ''
       or (r.account_id is not null and r.account_id <> p_account_id)
       or coalesce(r.sessions,0) < 0 or coalesce(r.engaged_sessions,0) < 0
       or coalesce(r.new_users,0) < 0 or coalesce(r.views,0) < 0
       or coalesce(r.events,0) < 0 or coalesce(r.key_events,0) < 0
  ) then
    raise exception 'invalid acquisition row' using errcode = '22023';
  end if;

  delete from public.dashboard_ga4_acquisition_daily d
  where d.client_id = v_client_id
    and d.account_id = p_account_id
    and d.metric_date between p_range_start and p_range_end;

  insert into public.dashboard_ga4_acquisition_daily (
    client_id, account_id, metric_date, channel_group, source_medium,
    sessions, engaged_sessions, new_users, views, events, key_events
  )
  select
    v_client_id, p_account_id, r.metric_date, r.channel_group, r.source_medium,
    sum(coalesce(r.sessions,0))::bigint,
    sum(coalesce(r.engaged_sessions,0))::bigint,
    sum(coalesce(r.new_users,0))::bigint,
    sum(coalesce(r.views,0))::bigint,
    sum(coalesce(r.events,0))::bigint,
    sum(coalesce(r.key_events,0))::numeric(20,6)
  from jsonb_to_recordset(v_rows) as r(
    account_id text, metric_date date, channel_group text, source_medium text,
    sessions bigint, engaged_sessions bigint, new_users bigint,
    views bigint, events bigint, key_events numeric
  )
  group by r.metric_date, r.channel_group, r.source_medium;

  get diagnostics v_row_count = row_count;

  insert into public.dashboard_sync_runs (
    client_id, source, idempotency_key, range_start, range_end, status, daily_rows
  ) values (
    v_client_id, 'ga4', p_idempotency_key, p_range_start, p_range_end, 'success', v_row_count
  );

  return jsonb_build_object(
    'success', true, 'idempotent', false, 'dataset', 'acquisition',
    'rows', v_row_count, 'range_start', p_range_start, 'range_end', p_range_end
  );
end;
$function$;

revoke all on function public.upsert_dashboard_ga4_acquisition_batch(text,text,text,date,date,jsonb) from public, anon, authenticated;
grant execute on function public.upsert_dashboard_ga4_acquisition_batch(text,text,text,date,date,jsonb) to service_role;

