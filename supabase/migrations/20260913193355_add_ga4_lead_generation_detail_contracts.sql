create or replace function public.get_dashboard_ga4_events(
  p_client_slug text,
  p_start_date date,
  p_end_date date,
  p_limit integer default 10,
  p_cursor jsonb default null
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $function$
declare
  v_client_id bigint;
  v_limit integer;
  v_days integer;
  v_cursor_count numeric;
  v_cursor_name text;
  v_result jsonb;
begin
  if p_start_date is null or p_end_date is null or p_start_date > p_end_date then
    raise exception 'invalid date range' using errcode = '22023';
  end if;
  v_days := p_end_date-p_start_date+1;
  if v_days > 366 then
    raise exception 'date range cannot exceed 366 days' using errcode = '22023';
  end if;

  v_limit := least(greatest(coalesce(p_limit,10),1),100);
  v_cursor_count := nullif(p_cursor ->> 'event_count','')::numeric;
  v_cursor_name := nullif(p_cursor ->> 'event_name','');
  v_client_id := private.dashboard_read_client_id(p_client_slug);

  with aggregated as (
    select e.event_name,sum(e.event_count)::numeric as event_count,sum(e.key_events)::numeric as key_events
    from public.dashboard_ga4_event_daily e
    where e.client_id=v_client_id and e.metric_date between p_start_date and p_end_date
    group by e.event_name
  ),
  enriched as (
    select a.event_name,a.event_count,a.event_count/v_days::numeric as daily_average,a.key_events,
      a.event_count*100/nullif(sum(a.event_count) over(),0) as share_of_total
    from aggregated a
  ),
  filtered as (
    select e.* from enriched e
    where v_cursor_count is null
       or e.event_count < v_cursor_count
       or (e.event_count=v_cursor_count and e.event_name>v_cursor_name)
  ),
  limited as (
    select f.* from filtered f order by f.event_count desc,f.event_name limit v_limit+1
  ),
  visible as (
    select l.* from limited l order by l.event_count desc,l.event_name limit v_limit
  )
  select jsonb_build_object(
    'items',coalesce((select jsonb_agg(to_jsonb(v) order by v.event_count desc,v.event_name) from visible v),'[]'::jsonb),
    'total_count',(select count(*) from enriched),
    'next_cursor',case when (select count(*) from limited)>v_limit then (
      select jsonb_build_object('event_count',v.event_count,'event_name',v.event_name)
      from visible v order by v.event_count asc,v.event_name desc limit 1
    ) else null end
  ) into v_result;

  return v_result;
end;
$function$;

