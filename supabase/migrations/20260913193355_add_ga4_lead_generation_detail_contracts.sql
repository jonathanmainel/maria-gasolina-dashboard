create or replace function public.get_dashboard_ga4_acquisition(
  p_client_slug text,
  p_start_date date,
  p_end_date date,
  p_limit integer default 10,
  p_cursor jsonb default null
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $function$
declare
  v_client_id bigint;
  v_limit integer;
  v_cursor_sessions numeric;
  v_cursor_channel text;
  v_cursor_source text;
  v_result jsonb;
begin
  if p_start_date is null or p_end_date is null or p_start_date > p_end_date then
    raise exception 'invalid date range' using errcode = '22023';
  end if;
  if p_end_date - p_start_date + 1 > 366 then
    raise exception 'date range cannot exceed 366 days' using errcode = '22023';
  end if;

  v_limit := least(greatest(coalesce(p_limit,10),1),100);
  v_cursor_sessions := nullif(p_cursor ->> 'sessions','')::numeric;
  v_cursor_channel := nullif(p_cursor ->> 'channel_group','');
  v_cursor_source := nullif(p_cursor ->> 'source_medium','');
  v_client_id := private.dashboard_read_client_id(p_client_slug);

  with acquisition as (
    select
      a.channel_group,
      a.source_medium,
      sum(a.sessions)::numeric as sessions,
      sum(a.engaged_sessions)::numeric as engaged_sessions,
      sum(a.new_users)::numeric as new_users,
      sum(a.views)::numeric as views,
      sum(a.events)::numeric as events,
      sum(a.key_events)::numeric as key_events
    from public.dashboard_ga4_acquisition_daily a
    where a.client_id=v_client_id and a.metric_date between p_start_date and p_end_date
    group by a.channel_group,a.source_medium
  ),
  leads as (
    select e.channel_group,e.source_medium,sum(e.event_count)::numeric as generate_leads
    from public.dashboard_ga4_event_daily e
    where e.client_id=v_client_id and e.metric_date between p_start_date and p_end_date
      and e.event_name='generate_lead'
    group by e.channel_group,e.source_medium
  ),
  enriched as (
    select
      a.channel_group,a.source_medium,a.sessions,a.engaged_sessions,a.new_users,a.views,a.events,a.key_events,
      coalesce(l.generate_leads,0)::numeric as generate_leads,
      a.engaged_sessions*100/nullif(a.sessions,0) as engagement_rate,
      coalesce(l.generate_leads,0)*100/nullif(a.sessions,0) as lead_rate
    from acquisition a
    left join leads l using(channel_group,source_medium)
  ),
  filtered as (
    select e.* from enriched e
    where v_cursor_sessions is null
       or e.sessions < v_cursor_sessions
       or (e.sessions = v_cursor_sessions and e.channel_group > v_cursor_channel)
       or (e.sessions = v_cursor_sessions and e.channel_group = v_cursor_channel and e.source_medium > v_cursor_source)
  ),
  limited as (
    select f.* from filtered f
    order by f.sessions desc,f.channel_group,f.source_medium
    limit v_limit+1
  ),
  visible as (
    select l.* from limited l
    order by l.sessions desc,l.channel_group,l.source_medium
    limit v_limit
  )
  select jsonb_build_object(
    'items',coalesce((select jsonb_agg(to_jsonb(v) order by v.sessions desc,v.channel_group,v.source_medium) from visible v),'[]'::jsonb),
    'total_count',(select count(*) from enriched),
    'next_cursor',case when (select count(*) from limited)>v_limit then (
      select jsonb_build_object('sessions',v.sessions,'channel_group',v.channel_group,'source_medium',v.source_medium)
      from visible v order by v.sessions asc,v.channel_group desc,v.source_medium desc limit 1
    ) else null end
  ) into v_result;

  return v_result;
end;
$function$;

