
create table if not exists public.dashboard_ga4_acquisition_daily (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.dashboard_clients(id) on delete cascade,
  account_id text not null,
  metric_date date not null,
  channel_group text not null,
  source_medium text not null,
  sessions bigint not null default 0 check (sessions >= 0),
  engaged_sessions bigint not null default 0 check (engaged_sessions >= 0),
  new_users bigint not null default 0 check (new_users >= 0),
  views bigint not null default 0 check (views >= 0),
  events bigint not null default 0 check (events >= 0),
  key_events numeric(20,6) not null default 0 check (key_events >= 0),
  ingested_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dashboard_ga4_acquisition_daily_unique
    unique (client_id, account_id, metric_date, channel_group, source_medium)
);

create index if not exists dashboard_ga4_acquisition_client_date_idx
  on public.dashboard_ga4_acquisition_daily (client_id, metric_date desc);
create index if not exists dashboard_ga4_acquisition_client_channel_idx
  on public.dashboard_ga4_acquisition_daily (client_id, channel_group, source_medium, metric_date desc);

alter table public.dashboard_ga4_acquisition_daily enable row level security;
