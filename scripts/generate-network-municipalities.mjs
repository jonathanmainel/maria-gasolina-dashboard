import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const [sourceRoot, outputArg] = process.argv.slice(2);
if (!sourceRoot) {
  throw new Error("Usage: node scripts/generate-network-municipalities.mjs <source-root> [output]");
}

const commit = "503e2f70bbf1b4b7ec0b1f68b09086ccc38fe861";
const municipalitiesPath = path.join(sourceRoot, "json", "municipios.json");
const statesPath = path.join(sourceRoot, "json", "estados.json");
const outputPath = outputArg
  ? path.resolve(outputArg)
  : path.resolve("supabase/functions/import-network-units/municipalities.ts");

const [municipalitiesRaw, statesRaw] = await Promise.all([
  readFile(municipalitiesPath),
  readFile(statesPath),
]);
const sourceChecksum = createHash("sha256").update(municipalitiesRaw).digest("hex").toUpperCase();
const statesChecksum = createHash("sha256").update(statesRaw).digest("hex").toUpperCase();
const decodeJson = (buffer) => buffer.toString("utf8").replace(/^\uFEFF/u, "");
const municipalities = JSON.parse(decodeJson(municipalitiesRaw));
const states = JSON.parse(decodeJson(statesRaw));
const statesByCode = new Map(states.map((state) => [state.codigo_uf, state.uf]));
const seenIbge = new Set();
const seenCityState = new Set();

const rows = municipalities.map((municipality) => {
  const state = statesByCode.get(municipality.codigo_uf);
  if (!state) throw new Error(`Missing state for ${municipality.codigo_ibge}`);
  if (seenIbge.has(municipality.codigo_ibge)) {
    throw new Error(`Duplicate IBGE code: ${municipality.codigo_ibge}`);
  }
  const cityState = `${state}|${municipality.nome}`;
  if (seenCityState.has(cityState)) {
    throw new Error(`Duplicate municipality: ${cityState}`);
  }
  if (municipality.latitude < -90 || municipality.latitude > 90) {
    throw new Error(`Invalid latitude: ${municipality.codigo_ibge}`);
  }
  if (municipality.longitude < -180 || municipality.longitude > 180) {
    throw new Error(`Invalid longitude: ${municipality.codigo_ibge}`);
  }
  seenIbge.add(municipality.codigo_ibge);
  seenCityState.add(cityState);
  return {
    ibgeCode: municipality.codigo_ibge,
    name: municipality.nome,
    state,
    latitude: municipality.latitude,
    longitude: municipality.longitude,
  };
});

const output = `// Generated by scripts/generate-network-municipalities.mjs. Do not edit manually.\n`
  + `// Source: https://github.com/kelvins/municipios-brasileiros/tree/${commit}\n`
  + `export const GEOGRAPHY_SOURCE = ${JSON.stringify({
    repository: "kelvins/municipios-brasileiros",
    commit,
    sourceFile: "json/municipios.json",
    sourceChecksum,
    statesFile: "json/estados.json",
    statesChecksum,
    municipalityCount: rows.length,
  }, null, 2)} as const;\n\n`
  + `export const MUNICIPALITIES = ${JSON.stringify(rows, null, 2)} as const;\n`;

await writeFile(outputPath, output, "utf8");
console.log(JSON.stringify({ outputPath, rows: rows.length, sourceChecksum, statesChecksum }));
